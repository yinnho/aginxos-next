pub fn font_init() -> [[u8; 8]; 128] {
    let mut bits = [[0u8; 8]; 128];
    for &(c, s) in GLYPHS {
        let mut row = 0usize;
        let mut col = 0usize;
        for &b in s.as_bytes() {
            if b == b'\n' { row += 1; col = 0; continue; }
            if row >= 8 { break; }
            if col < 5 && b == b'#' { bits[c as usize & 127][row] |= 0x10 >> col; }
            col += 1;
        }
    }
    bits
}
